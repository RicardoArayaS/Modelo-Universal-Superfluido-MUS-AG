    # --------------------------------------------------------------------------
    # FASE 1: DESPEJE DEL GRADIENTE DE PRESIÓN (Ecuación de Euler)
    # --------------------------------------------------------------------------
    print("[FASE 1] FORMALIZACIÓN DEL GRADIENTE DE PRESIÓN (Postulado II):")
    print(" 1. Ecuación de Euler para súper-flujo : (v · ∇)v = -(1/rho)∇P")
    print(" 2. Perfil de velocidad del vórtice    : v(r) = Γ / (2*pi*r)")
    print(" 3. Derivada de presión radial (dP/dr) : rho * (Γ^2 / (4*pi^2 * r^3))")
    print(" 4. Integrando desde infinito hasta r  : P(r) = P_pm - (rho * Γ^2) / (8*pi^2 * r^2)")
    print("\n -> CONCLUSIÓN: La atracción es matemáticamente una caída de presión.")
    print("    El fluido exterior (P_pm) empuja la materia hacia el centro.\n")

    # --------------------------------------------------------------------------
    # FASE 2: DEMOSTRACIÓN DE LA CUANTIZACIÓN (Ecuación de Helmholtz)
    # --------------------------------------------------------------------------
    print("[FASE 2] LA ILUSIÓN DE LA PARTÍCULA Y LA CUANTIZACIÓN (Postulado III):")
    print(" 1. Ecuación de perturbación de presión : ∇^2(δP) + k^2(δP) = 0")
    print(" 2. Condición de contorno topológica    : Superficie esférica cerrada de la Capa Límite.")
    print(" 3. Soluciones matemáticas posibles     : Armónicos Esféricos Y_l^m(θ, φ)")
    print(" 4. Restricción escalar                 : Los parámetros 'l' y 'm' DEBEN ser números enteros.")

