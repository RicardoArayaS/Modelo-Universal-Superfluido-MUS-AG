    print("    Son números enteros dictados mecánicamente por los modos de vibración")
    print("    (nodos de tensión) permitidos en una capa límite esférica cerrada.")

    print("="*75)
    print("VEREDICTO MATEMÁTICO: LA MATERIA ES TOPOLOGÍA. LA PARTÍCULA HA SIDO DESCARTADA.")
