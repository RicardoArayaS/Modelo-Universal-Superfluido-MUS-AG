import numpy as np
from scipy.integrate import solve_ivp

# ==============================================================================
# 1. PARÁMETROS DEL MEDIO FLUIDO
# ==============================================================================
MU_SOL_NASA = 1.32712440042e20
K_MUS = 6.67430e-11

# EL BISTURÍ TÉRMICO (Tu coeficiente estabilizado con la malla exterior)
coef_friccion_acustica = 0.0

# ==============================================================================
# 2. VECTORES DE ESTADO GEOMÉTRICOS PUROS (07-OCT-2026) -> Metros y Metros/Segundo
# ==============================================================================
# 0. EL SOL
pos_sol = np.array([0.0, 0.0, 0.0])
vel_sol = np.array([0.0, 0.0, 0.0])

# 1. COMETA 1P/HALLEY
pos_halley = np.array([-2.895097643436489e12, 4.109321132201368e12, -1.474017155032063e12])
vel_halley = np.array([949.8197956848108, 205.1336671531960, 228.5981963994371])

# --- GIGANTES GASEOSOS ---
# 2. JÚPITER (Barycenter)
m_jupiter = 1.89813e27
pos_jupiter = np.array([-5.273294994939023e11, 5.937924652734375e11, 9.331669801375389e9])
vel_jupiter = np.array([-9929.648400413264, -8073.387100164961, 255.7041768542203])

# 3. SATURNO (Barycenter)
m_saturno = 5.68319e26
pos_saturno = np.array([1.383924891515096e12, 2.691993743525907e11, -5.977692512280234e10])
vel_saturno = np.array([-2380.078624745514, 9457.322113893230, -69.98482833616704])

# 4. URANO (Barycenter)
m_urano = 8.68103e25
pos_urano = np.array([1.332851628893289e12, 2.584790196362720e12, -7.682293550095558e9])
vel_urano = np.array([-6113.132462538874, 2799.639158115922, 89.69300256794610])

# 5. NEPTUNO (Barycenter)
m_neptuno = 1.02410e26
pos_neptuno = np.array([4.463482057078790e12, 2.092971313769050e11, -1.071697064036952e11])
vel_neptuno = np.array([-299.8563627144397, 5457.164839870210, -105.5795116897829])

# --- SISTEMA INTERNO ---
# 6. MERCURIO (Barycenter)
m_mercurio = 3.301e23
pos_mercurio = np.array([1.672473217193891e10, -6.544358285398847e10, -6.882250412941065e9])
vel_mercurio = np.array([37428.78164773122, 14545.09121458015, -2244.148713182004])

# 7. VENUS (Barycenter)
m_venus = 4.8673e24
pos_venus = np.array([1.083362152920484e11, 5.725953253171356e9, -6.172145925285747e9])
vel_venus = np.array([-1991.939831848415, 34812.32175541486, 593.2644586999025])

# 8. TIERRA-LUNA (Barycenter)
m_tierra_luna = 6.0457e24
pos_tierra_luna = np.array([1.454852118693951e11, 3.459564525758239e10, -2.983466532563791e6])
vel_tierra_luna = np.array([-7374.727905913709, 28868.71264752120, -1.717838813789285])

# 9. MARTE (Barycenter)
m_marte = 6.4169e23
pos_marte = np.array([6.974145178171263e9, 2.340591768411301e11, 4.734016281543136e9])
vel_marte = np.array([-23300.73274042429, 2779.254802901602, 629.5792676248391])

# Empaquetado Total (10 Cuerpos)
masas_array = [0.0, 2.2e14, m_jupiter, m_saturno, m_urano, m_neptuno,
               m_mercurio, m_venus, m_tierra_luna, m_marte]

estado_inicial = np.concatenate((
    pos_sol, pos_halley, pos_jupiter, pos_saturno, pos_urano, pos_neptuno, pos_mercurio, pos_venus, pos_tierra_luna, pos_marte,
    vel_sol, vel_halley, vel_jupiter, vel_saturno, vel_urano, vel_neptuno, vel_mercurio, vel_venus, vel_tierra_luna, vel_marte
))

target_nasa_halley = np.array([-2.893946732845277e12, 4.109566364426430e12, -1.473739644906284e12])

# ==============================================================================
# 3. NÚCLEO FÍSICO N-CUERPOS (Ecosistema Absoluto MUS-AG)
# ==============================================================================
def gradientes_malla_absoluta(t, estado):
    pos = estado[:30].reshape((10, 3))
    vel = estado[30:].reshape((10, 3))
    a_total = np.zeros((10, 3))

    for i in range(10):
        # Fricción base acústica en el sustrato
        a_total[i] += -coef_friccion_acustica * vel[i]

        for j in range(10):
            if i != j:
                r_inter = pos[j] - pos[i]
                dist_inter = max(np.linalg.norm(r_inter), 1.0)

                # Succión del Vórtice Central (Sol)
                if j == 0:
                    a_total[i] += MU_SOL_NASA * (r_inter / dist_inter**3)
                # Interferencia Topológica Planetaria
                else:
                    a_total[i] += K_MUS * masas_array[j] * (r_inter / dist_inter**3)

    return np.concatenate((vel.flatten(), a_total.flatten()))

# ==============================================================================
# 4. EJECUCIÓN (Cálculo Relativo al Sol Desplazado)
# ==============================================================================
print(">>> INICIANDO MOTOR MUS-AG V3.6 (SISTEMA SOLAR COMPLETO C=1) <<<")
t_span = (0, 14 * 24 * 3600)
solucion = solve_ivp(gradientes_malla_absoluta, t_span, estado_inicial,
                     method='DOP853', rtol=1e-13, atol=1e-13)

# Extraer posiciones absolutas finales (Índice 0 = Sol, Índice 1 = Halley)
pos_final_sol = solucion.y[0:3, -1]
pos_final_halley = solucion.y[3:6, -1]

# CÁLCULO HELIOCÉNTRICO REAL
pos_halley_heliocentrica = pos_final_halley - pos_final_sol

delta_vectores = pos_halley_heliocentrica - target_nasa_halley
desviacion_total_km = np.linalg.norm(delta_vectores) / 1000.0

