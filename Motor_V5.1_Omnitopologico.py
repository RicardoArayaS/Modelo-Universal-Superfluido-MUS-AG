import numpy as np
from scipy.integrate import solve_ivp

def motor_mus_ag_universal(cuerpos_dict, dias_simulacion, dt_eval=None):
    """
    Simulador Universal MUS-AG.
    Integra simultáneamente la navegación pasiva de N-cuerpos y la compresión
    convectiva en campos fuertes, erradicando el espacio-tiempo curvo.
    """
    print(">>> INICIANDO PROTOCOLO C=1: MOTOR MUS-AG V5.0 (OMNI-TOPOLÓGICO) <<<")
    print("="*75)

    # 1. PARÁMETROS DEL MEDIO UNIVERSAL (Pre-materia)
    C_ACUSTICO = 299792458.0  # Límite incompresible (m/s)

    n_cuerpos = len(cuerpos_dict)
    nombres = list(cuerpos_dict.keys())

    # Extraer masas topológicas (capacidades de succión G*M) y estados
    mu_array = np.array([cuerpos_dict[n]["mu"] for n in nombres])

    estado_inicial = []
    for n in nombres:
        estado_inicial.extend(cuerpos_dict[n]["pos"])
        estado_inicial.extend(cuerpos_dict[n]["vel"])
    estado_inicial = np.array(estado_inicial, dtype=np.float64)

    # 2. VECTORIZADOR SISTÉMICO UNIVERSAL
    def gradiente_omni_topologico(t, estado):
        # Desempaquetar vector de estado [pos_x, pos_y, pos_z, vel_x, vel_y, vel_z, ...]
        estado_matriz = estado.reshape((n_cuerpos, 6))
        posiciones = estado_matriz[:, 0:3]
        velocidades = estado_matriz[:, 3:6]

        aceleraciones = np.zeros_like(posiciones)

        # Calcular el empuje neto sobre el cuerpo 'i' generado por todos los sumideros 'j'
        for i in range(n_cuerpos):
            acel_neta_i = np.zeros(3)

            for j in range(n_cuerpos):
                if i == j:
                    continue

                # Vector de posición relativa (del cuerpo i hacia el sumidero j)
                r_vec = posiciones[j] - posiciones[i]
                r_mag = np.linalg.norm(r_vec)

                # Vector de velocidad relativa
                v_vec = velocidades[i] - velocidades[j]

                # A. GRADIENTE LINEAL BASE (Motor V3.6 - El Embudo Isobárico)
                # Equivalente hidrodinámico a 1/r^2
                empuje_base = (mu_array[j] / r_mag**3) * r_vec

                # B. GRADIENTE CONVECTIVO NO LINEAL (Motor V4.0 - Campos Fuertes)
                # Momento angular específico (flujo cruzado)
                h_vec = np.cross(r_vec, v_vec)
                h_cuadrado = np.dot(h_vec, h_vec)

                # Efecto Bernoulli / Compresión Convectiva equivalente a 1/r^4
                factor_convectivo = (3.0 * mu_array[j] * h_cuadrado) / ((C_ACUSTICO**2) * (r_mag**5))
                empuje_convectivo = factor_convectivo * r_vec

                # La suma unifica ambos extremos en un solo ecosistema topológico
                acel_neta_i += empuje_base + empuje_convectivo

            aceleraciones[i] = acel_neta_i

        # Reempaquetar a vector 1D
        derivadas = np.zeros_like(estado_matriz)
        derivadas[:, 0:3] = velocidades
        derivadas[:, 3:6] = aceleraciones
        return derivadas.flatten()

    # 3. EJECUCIÓN DEL DESCENSO DE GRADIENTE
    t_span = (0.0, dias_simulacion * 24 * 3600)
    if dt_eval is not None:
        t_eval = np.arange(t_span[0], t_span[1], dt_eval * 24 * 3600)
    else:
        t_eval = None

    print(f" -> Integrando ecosistema topológico de {n_cuerpos} vórtices...")
    print(" -> Autoadaptación activada: V3.6 (Débil) y V4.0 (Fuerte) operando simultáneamente.")

    solucion = solve_ivp(gradiente_omni_topologico, t_span, estado_inicial,
                         method='DOP853', t_eval=t_eval, rtol=1e-13, atol=1e-13)

    print("="*75)
    print("DICTAMEN C=1: NAVEGACIÓN UNIVERSAL COMPLETADA")
    print("="*75)

    return solucion

