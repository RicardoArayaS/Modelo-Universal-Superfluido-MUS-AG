# ==============================================================================
# MOTOR CINÉTICO MUS-AG: EXPERIMENTUM CRUCIS (SIMULADOR DE NAVEGACIÓN)
# Dinámica de Fluidos Orbitales - Trayectoria del Cometa por Gradiente de Presión
# ==============================================================================

import numpy as np
import plotly.graph_objects as go
from scipy.integrate import solve_ivp

def simulador_cinetico_mus_ag():
    print("INICIANDO PROTOCOLO MUS-AG: MOTOR CINÉTICO DE FLUIDOS")
    print("="*75)

    # 1. DEFINICIÓN DEL ECOSISTEMA (Sumideros / Macro-vórtices)
    # Formato: [Nombre, Pos_X, Pos_Y, Masa_Topologica (Caída de Presión), Capa_Limite]
    cuerpos = [
        ["Estrella Central (Macro-Sumidero)", 0.0, 0.0, 200.0, 0.8],
        ["Planeta Gigante", 4.0, 3.0, 50.0, 0.5],
        ["Planeta Denso", -5.0, -2.0, 30.0, 0.4]
    ]

    # 2. FUNCIÓN DE GRADIENTE DE PRESIÓN (El empuje del Súper-flujo)
    # Calcula la fuerza hidrostática en cualquier punto (x, y)
    def calcular_gradiente(x, y):
        grad_x, grad_y = 0.0, 0.0
        for cuerpo in cuerpos:
            cx, cy, masa, capa_limite = cuerpo[1], cuerpo[2], cuerpo[3], cuerpo[4]
            dist_sq = (x - cx)**2 + (y - cy)**2
            dist = np.sqrt(dist_sq)

            # Condición MUS-AG: El fluido choca con la Capa Límite (evita la singularidad)
            if dist < capa_limite:
                dist = capa_limite

            # Magnitud del gradiente de presión empujando hacia el sumidero
            # Derivada de la caída de presión escalar: dP/dr = 2 * masa / dist^3
            fuerza_empuje = (2 * masa) / (dist**3)

            # Vectorizando el empuje hidrostático hacia el fondo del embudo
            grad_x += fuerza_empuje * (cx - x)
            grad_y += fuerza_empuje * (cy - y)
        return grad_x, grad_y

    # 3. MOTOR DE ITERACIÓN TEMPORAL (Ecuaciones diferenciales del fluido)
    # y = [pos_x, pos_y, vel_x, vel_y]
    def derivadas_movimiento(t, estado):
        x, y, vx, vy = estado
        # La aceleración es estrictamente el Gradiente de Presión local empujando el V_ef
        ax, ay = calcular_gradiente(x, y)
        return [vx, vy, ax, ay]

    # 4. INYECCIÓN DEL COMETA (Condiciones Iniciales)
    # Entrando desde el borde del cuadrante escalar
    pos_inicial = [-8.0, 6.0]
    vel_inicial = [1.5, -0.5] # Velocidad propia inicial cruzando la corriente
    estado_inicial = pos_inicial + vel_inicial

    # Tiempo de simulación (bucle de la balsa en la corriente)
    t_span = (0, 10)
    t_eval = np.linspace(t_span[0], t_span[1], 500)

    # Resolviendo la trayectoria determinista mediante el descenso de gradiente
    solucion = solve_ivp(derivadas_movimiento, t_span, estado_inicial, t_eval=t_eval, rtol=1e-6)
    ruta_x = solucion.y[0]
    ruta_y = solucion.y[1]

    # 5. RENDERIZADO TOPOGRÁFICO 3D (El Mapa de Isobaras Cósmicas)
    grid_size = 200
    malla_x = np.linspace(-10, 10, grid_size)
    malla_y = np.linspace(-10, 10, grid_size)
    X, Y = np.meshgrid(malla_x, malla_y)
    Z_presion = np.zeros_like(X)

    # Mapeo del lecho de presiones para la gráfica
    for cuerpo in cuerpos:
        cx, cy, masa, capa_limite = cuerpo[1], cuerpo[2], cuerpo[3], cuerpo[4]
        dist = np.sqrt((X - cx)**2 + (Y - cy)**2)
        dist = np.where(dist < capa_limite, capa_limite, dist)
        Z_presion -= masa / (dist**2)

    Z_presion = np.clip(Z_presion, -500, 0)

    # 6. CALCULAR ALTITUD TOPOGRÁFICA DE LA RUTA DEL COMETA
    # Para que la línea de la trayectoria del cometa navegue sobre la malla 3D
    ruta_z = np.zeros_like(ruta_x)
    for i in range(len(ruta_x)):
        z_local = 0
        for cuerpo in cuerpos:
            cx, cy, masa, capa_limite = cuerpo[1], cuerpo[2], cuerpo[3], cuerpo[4]
            d = np.sqrt((ruta_x[i] - cx)**2 + (ruta_y[i] - cy)**2)
            d = max(d, capa_limite)
            z_local -= masa / (d**2)
        ruta_z[i] = max(z_local, -500)

    # 7. CONSTRUCCIÓN DE LA INTERFAZ VISUAL
    fig = go.Figure()

    # Añadir el Súper-flujo Incompresible (Superficie)
    fig.add_trace(go.Surface(
        z=Z_presion, x=X, y=Y,
        colorscale='Viridis',
        opacity=0.8,
        showscale=False,
        name="Presión Absoluta (P_pm)"
    ))

    # Añadir la Trayectoria del Cometa (Navegación por Gradiente)
    fig.add_trace(go.Scatter3d(
        x=ruta_x, y=ruta_y, z=ruta_z,
        mode='lines+markers',
        marker=dict(size=2, color='red'),
        line=dict(color='yellow', width=5),
        name="Núcleo del Cometa (Ruta MUS-AG)"
    ))

    # Añadir Marcadores de los Sumideros
    for cuerpo in cuerpos:
        fig.add_trace(go.Scatter3d(
            x=[cuerpo[1]], y=[cuerpo[2]], z=[0],
            mode='markers+text',
            text=[cuerpo[0]],
            textposition="top center",
            marker=dict(size=6, color='cyan'),
            name=cuerpo[0]
        ))

    fig.update_layout(
        title='Experimentum Crucis MUS-AG: Descenso de Gradiente del Cometa',
        scene=dict(
            xaxis_title='Eje X',
            yaxis_title='Eje Y',
            zaxis_title='Caída de Presión Hidrostática',
            aspectratio=dict(x=1, y=1, z=0.6),
            camera=dict(eye=dict(x=-1.5, y=-1.5, z=1.2))
        ),
        margin=dict(l=0, r=0, b=0, t=40),
        legend=dict(x=0, y=1)
    )

    print("-> Cálculo de Flujo Volumétrico completado.")
    print("-> El cometa ha sido arrastrado por la corriente hidrostática, eludiendo la tracción newtoniana a distancia.")
    fig.show()

if __name__ == "__main__":
    simulador_cinetico_mus_ag()

# ==============================================================================
# MOTOR ASTROFÍSICO MUS-AG: MAPA TOPOGRÁFICO INTERACTIVO 3D (N-CUERPOS)
# Sistema: Júpiter, Lunas Galileanas y un Cometa Errante
# Objetivo: Demostrar flotabilidad hidrodinámica estable con telemetría en vivo.
# Renderizador: Plotly Graph Objects (Rotable, Zoom, Hover Data)
# ==============================================================================

import numpy as np
import plotly.graph_objects as go

def simulacion_mus_ag_interactiva_3d():
    print("INICIANDO PROTOCOLO C=1: MOTOR TOPOGRÁFICO INTERACTIVO MUS-AG")
    print("Generando malla espacial y calculando isóbaras...")
    print("="*75)

    # 1. PARÁMETROS DEL MEDIO UNIVERSAL Y MACRO-SUMIDERO
    k_gradiente = 6.67430e-11 # Constante de conversión a Gradiente MUS-AG
    M_jupiter = 1.898e27 # kg (Resistencia Hidrodinámica del sumidero central)

    # 2. DEFINICIÓN DE ENTIDADES (Coordenadas en metros, Velocidades en m/s)
    entidades = {
        "Ío": {"pos": np.array([4.217e8, 0.0, 0.0]), "vel": np.array([0.0, 17334.0, 0.0]), "color": "#FFD700"},
        "Europa": {"pos": np.array([6.711e8, 0.0, 0.0]), "vel": np.array([0.0, 13740.0, 0.0]), "color": "#FFFFFF"},
        "Ganimedes": {"pos": np.array([1.070e9, 0.0, 0.0]), "vel": np.array([0.0, 10880.0, 0.0]), "color": "#00FFFF"},
        "Calisto": {"pos": np.array([1.882e9, 0.0, 0.0]), "vel": np.array([0.0, 8200.0, 0.0]), "color": "#A9A9A9"},
        "Cometa Errante": {"pos": np.array([-2.5e9, -2.5e9, 1.0e8]), "vel": np.array([15000.0, 5000.0, -1000.0]), "color": "#FF0000"}
    }

    # Configuración de simulación
    dias_simulacion = 30
    dt = 3600 # Paso de 1 hora
    pasos = int((dias_simulacion * 24 * 3600) / dt)

    # Diccionario para almacenar el historial de posiciones para el renderizado
    historial = {nombre: {"x": np.zeros(pasos), "y": np.zeros(pasos), "z": np.zeros(pasos)} for nombre in entidades}

    print(f" -> Calculando navegación por gradientes ({dias_simulacion} días / {pasos} iteraciones)...")

    # 3. MOTOR DE CÁLCULO C=1 (F = ΔP * A)
    for i in range(pasos):
        for nombre, datos in entidades.items():
            pos = datos["pos"]
            vel = datos["vel"]

            distancia_al_sumidero = np.linalg.norm(pos)
            vector_direccion = -pos / distancia_al_sumidero

            # El gradiente de presión empuja al objeto hacia el Macro-Sumidero
            aceleracion_gradiente = k_gradiente * M_jupiter / (distancia_al_sumidero**2)
            vector_aceleracion = vector_direccion * aceleracion_gradiente

            # Navegación pasiva hidrodinámica
            vel = vel + vector_aceleracion * dt
            pos = pos + vel * dt

            # Actualizar y registrar
            entidades[nombre]["pos"] = pos
            entidades[nombre]["vel"] = vel
            historial[nombre]["x"][i] = pos[0]
            historial[nombre]["y"][i] = pos[1]
            historial[nombre]["z"][i] = pos[2]

    print(" -> Ecuaciones resueltas. Estructura de isóbaras intacta.")
    print(" -> Renderizando mapa topográfico interactivo...\n")

    # 4. RENDERIZADO VISUAL INTERACTIVO (PLOTLY)
    fig = go.Figure()

    # Inyectar el Macro-Sumidero (Júpiter) en el centro (0,0,0)
    fig.add_trace(go.Scatter3d(
        x=[0], y=[0], z=[0],
        mode='markers',
        marker=dict(size=12, color='orange', symbol='circle'),
        name='Júpiter (Sumidero)',
        hovertemplate="<b>Macro-Sumidero</b><br>Centro de Presión<extra></extra>"
    ))

    # Inyectar las estelas de navegación (órbitas y trayectoria del cometa)
    for nombre in entidades:
        color = entidades[nombre]["color"]
        # Convertir índices a días para la telemetría
        dias_hover = [f"Día {int((i*dt)/86400)}" for i in range(pasos)]

        fig.add_trace(go.Scatter3d(
            x=historial[nombre]["x"],
            y=historial[nombre]["y"],
            z=historial[nombre]["z"],
            mode='lines',
            line=dict(color=color, width=3 if nombre == 'Cometa Errante' else 2, dash='solid' if nombre != 'Cometa Errante' else 'dot'),
            name=nombre,
            text=dias_hover,
            hovertemplate="<b>" + nombre + "</b><br>%{text}<br>X: %{x:.2e} m<br>Y: %{y:.2e} m<br>Z: %{z:.2e} m<extra></extra>"
        ))

        # Inyectar la posición final de cada entidad (esfera sólida final)
        fig.add_trace(go.Scatter3d(
            x=[historial[nombre]["x"][-1]],
            y=[historial[nombre]["y"][-1]],
            z=[historial[nombre]["z"][-1]],
            mode='markers',
            marker=dict(size=5, color=color),
            showlegend=False,
            hoverinfo='skip'
        ))

    # Configuración del entorno 3D (Fondo espacial)
    fig.update_layout(
        title=dict(text="MUS-AG: Navegación por Gradientes (Entorno Interactivo)", font=dict(color='white', size=18)),
        scene=dict(
            xaxis_title='Eje X (m)',
            yaxis_title='Eje Y (m)',
            zaxis_title='Eje Z (m)',
            xaxis=dict(backgroundcolor="black", gridcolor="gray", showbackground=True, zerolinecolor="white"),
            yaxis=dict(backgroundcolor="black", gridcolor="gray", showbackground=True, zerolinecolor="white"),
            zaxis=dict(backgroundcolor="black", gridcolor="gray", showbackground=True, zerolinecolor="white"),
            bgcolor="black"
        ),
        paper_bgcolor="black",
        font=dict(color="white"),
        margin=dict(l=0, r=0, b=0, t=50),
        legend=dict(x=0, y=1, font=dict(color="white", size=12))
    )

    fig.show()
    print("="*75)
    print("DICTAMEN C=1: UTILICE EL RATÓN PARA ROTAR (CLICK IZQUIERDO), HACER ZOOM (RUEDA)")
    print("Y PASAR EL CURSOR SOBRE LAS ISÓBARAS PARA VER LA TELEMETRÍA EXACTA.")
    print("="*75)

if __name__ == "__main__":
    simulacion_mus_ag_interactiva_3d()

# ==============================================================================
# MOTOR ASTROFÍSICO MUS-AG: FLOTABILIDAD EN ECOSISTEMAS BINARIOS (TIERRA-LUNA)
# Sistema: Tierra (Macro-Sumidero), Luna (Sumidero Menor) y Satélite (Micro-Vórtice)
# Objetivo: Demostrar topografía dinámica y erradicación de la tracción recíproca.
# ==============================================================================

import numpy as np
import plotly.graph_objects as go

def simulacion_mus_ag_tierra_luna():
    print("INICIANDO PROTOCOLO C=1: MOTOR TOPOGRÁFICO BINARIO MUS-AG")
    print("ALERTA: Erradicando tracción mutua del micro-vórtice (Satélite).")
    print("="*75)

    # 1. PARÁMETROS DEL MEDIO UNIVERSAL
    k_gradiente = 6.67430e-11 # Constante de conversión a Gradiente MUS-AG
    M_tierra = 5.972e24 # kg (Resistencia Hidrodinámica Tierra)
    M_luna = 7.348e22   # kg (Resistencia Hidrodinámica Luna)

    # 2. DEFINICIÓN DE ENTIDADES (Coordenadas en metros, Velocidades en m/s)
    # Satélite inyectado en una órbita altamente elíptica y perturbable (Trans-lunar)
    entidades = {
        "Tierra": {"pos": np.array([0.0, 0.0, 0.0]), "vel": np.array([0.0, 0.0, 0.0]), "color": "#0088FF", "M": M_tierra, "tipo": "Macro-Sumidero"},
        "Luna": {"pos": np.array([3.844e8, 0.0, 0.0]), "vel": np.array([0.0, 1022.0, 0.0]), "color": "#AAAAAA", "M": M_luna, "tipo": "Sumidero Menor"},
        "Satélite Orbiter": {"pos": np.array([6.771e6, 0.0, 0.0]), "vel": np.array([0.0, 10500.0, 1500.0]), "color": "#FF00FF", "M": 0, "tipo": "Micro-Vórtice (Pasivo)"}
    }

    # Configuración de simulación (7 días para observar la oscilación del gradiente)
    dias_simulacion = 7
    dt = 600 # Paso de 10 minutos (mayor resolución para perturbaciones)
    pasos = int((dias_simulacion * 24 * 3600) / dt)

    historial = {nombre: {"x": np.zeros(pasos), "y": np.zeros(pasos), "z": np.zeros(pasos), "grad_neto": np.zeros(pasos)} for nombre in entidades}

    print(f" -> Calculando navegación hidro-topográfica ({dias_simulacion} días / {pasos} iteraciones)...")

    # 3. MOTOR DE CÁLCULO C=1 (Navegación Pasiva vs Activa)
    for i in range(pasos):
        # Primero, calculamos la dinámica del Sumidero Menor (Luna) respecto al Macro-Sumidero (Tierra)
        pos_luna = entidades["Luna"]["pos"]
        dist_luna_tierra = np.linalg.norm(pos_luna)
        acel_luna = (-pos_luna / dist_luna_tierra) * (k_gradiente * M_tierra / dist_luna_tierra**2)

        entidades["Luna"]["vel"] += acel_luna * dt
        entidades["Luna"]["pos"] += entidades["Luna"]["vel"] * dt

        # Segundo, el Satélite surfea el gradiente COMBINADO de ambos sumideros
        pos_sat = entidades["Satélite Orbiter"]["pos"]

        # Gradiente Tierra
        dist_sat_tierra = np.linalg.norm(pos_sat)
        grad_tierra = (-pos_sat / dist_sat_tierra) * (k_gradiente * M_tierra / dist_sat_tierra**2)

        # Gradiente Luna
        vector_sat_luna = entidades["Luna"]["pos"] - pos_sat
        dist_sat_luna = np.linalg.norm(vector_sat_luna)
        grad_luna = (vector_sat_luna / dist_sat_luna) * (k_gradiente * M_luna / dist_sat_luna**2)

        # Vectorización Sistémica (Gradiente Neto Total)
        grad_neto = grad_tierra + grad_luna

        # Navegación del satélite
        entidades["Satélite Orbiter"]["vel"] += grad_neto * dt
        entidades["Satélite Orbiter"]["pos"] += entidades["Satélite Orbiter"]["vel"] * dt

        # Registro topográfico y telemetría
        for nombre in entidades:
            historial[nombre]["x"][i] = entidades[nombre]["pos"][0]
            historial[nombre]["y"][i] = entidades[nombre]["pos"][1]
            historial[nombre]["z"][i] = entidades[nombre]["pos"][2]

        # Guardar magnitud del gradiente neto para el satélite
        historial["Satélite Orbiter"]["grad_neto"][i] = np.linalg.norm(grad_neto)

    print(" -> Resolución de isóbaras binarias completada.")
    print(" -> Renderizando telemetría interactiva...\n")

    # 4. RENDERIZADO VISUAL INTERACTIVO (PLOTLY)
    fig = go.Figure()

    for nombre in entidades:
        color = entidades[nombre]["color"]
        tipo = entidades[nombre]["tipo"]

        # Texto de telemetría dinámica para el Hover
        if nombre == "Satélite Orbiter":
            hover_text = [
                f"<b>{nombre}</b><br>"
                f"Tipo: {tipo}<br>"
                f"Día: {(i*dt)/86400:.1f}<br>"
                f"∇P Neto (Aceleración de arrastre): {historial[nombre]['grad_neto'][i]:.4f} m/s²<br>"
                f"<span style='color:#FF4444'>Perturbación causada a Tierra/Luna: 0.00%</span><br>"
                f"<i>(Flotabilidad pasiva confirmada)</i><extra></extra>"
                for i in range(pasos)
            ]
            line_width = 2
        else:
            hover_text = [
                f"<b>{nombre}</b><br>"
                f"Tipo: {tipo}<br>"
                f"Día: {(i*dt)/86400:.1f}<br>"
                f"Generador de macro-embudo isobárico.<extra></extra>"
                for i in range(pasos)
            ]
            line_width = 4 if nombre == "Tierra" else 3

        fig.add_trace(go.Scatter3d(
            x=historial[nombre]["x"],
            y=historial[nombre]["y"],
            z=historial[nombre]["z"],
            mode='lines',
            line=dict(color=color, width=line_width),
            name=nombre,
            text=hover_text,
            hovertemplate="%{text}"
        ))

        # Esfera sólida en la posición final
        fig.add_trace(go.Scatter3d(
            x=[historial[nombre]["x"][-1]],
            y=[historial[nombre]["y"][-1]],
            z=[historial[nombre]["z"][-1]],
            mode='markers',
            marker=dict(size=8 if nombre == "Tierra" else (5 if nombre == "Luna" else 3), color=color),
            showlegend=False,
            hoverinfo='skip'
        ))

    # Configuración del entorno espacial
    fig.update_layout(
        title=dict(text="MUS-AG: Navegación por Gradientes en Sistema Binario (Tierra-Luna)", font=dict(color='white', size=16)),
        scene=dict(
            xaxis_title='Eje X (m)', yaxis_title='Eje Y (m)', zaxis_title='Eje Z (m)',
            xaxis=dict(backgroundcolor="black", gridcolor="#333333", showbackground=True, zerolinecolor="white"),
            yaxis=dict(backgroundcolor="black", gridcolor="#333333", showbackground=True, zerolinecolor="white"),
            zaxis=dict(backgroundcolor="black", gridcolor="#333333", showbackground=True, zerolinecolor="white"),
            bgcolor="black"
        ),
        paper_bgcolor="black", font=dict(color="white"), margin=dict(l=0, r=0, b=0, t=50),
        legend=dict(x=0, y=1, font=dict(color="white", size=12))
    )

    fig.show()

    # DICTAMEN FINAL DEL VECTORIZADOR
    print("="*75)
    print("DICTAMEN C=1: EL SATÉLITE ES UN NAVEGANTE PASIVO.")
    print("La telemetría demuestra la fluctuación del Gradiente de Presión Neto (∇P).")
    print("Se erradica el tensor de acción/reacción: el satélite NO tracciona a la Tierra.")
    print("La órbita caótica es solo la búsqueda de Puntos Muertos Hidrostáticos.")
    print("="*75)

if __name__ == "__main__":
    simulacion_mus_ag_tierra_luna()